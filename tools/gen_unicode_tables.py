# Generates src/unicode_tables.h from Python's unicodedata:
#   - word character ranges: general categories L* (letters), Mn and Mc
#     (combining marks) except variation selectors, and Nd (digits)
#   - simple one-to-one lowercase mappings, as runs of (lo, hi, stride, delta)
# Usage: python3 tools/gen_unicode_tables.py > src/unicode_tables.h

import sys
import unicodedata

MAX_CP = 0x10FFFF


def is_surrogate(cp):
    return 0xD800 <= cp <= 0xDFFF


def is_variation_selector(cp):
    return 0xFE00 <= cp <= 0xFE0F or 0xE0100 <= cp <= 0xE01EF


def word_ranges():
    ranges = []
    for cp in range(MAX_CP + 1):
        if is_surrogate(cp):
            continue
        cat = unicodedata.category(chr(cp))
        if cat[0] == "L" or (cat in ("Mn", "Mc", "Nd")
                             and not is_variation_selector(cp)):
            if ranges and ranges[-1][1] == cp - 1:
                ranges[-1][1] = cp
            else:
                ranges.append([cp, cp])
    return ranges


def simple_lower(cp):
    # str.lower() applies the full mapping. The only code point whose full
    # lowercase is longer than one character is U+0130, whose simple mapping
    # (UnicodeData.txt field 13) is U+0069, the first character of the full one.
    low = chr(cp).lower()
    return ord(low[0])


def lower_runs():
    runs = []  # [lo, hi, stride, delta]
    for cp in range(MAX_CP + 1):
        if is_surrogate(cp):
            continue
        low = simple_lower(cp)
        if low == cp:
            continue
        delta = low - cp
        if runs:
            r = runs[-1]
            if r[3] == delta:
                gap = cp - r[1]
                if r[0] == r[1] and gap in (1, 2):
                    r[1], r[2] = cp, gap
                    continue
                if gap == r[2]:
                    r[1] = cp
                    continue
        runs.append([cp, cp, 1, delta])
    return runs


def main():
    words = word_ranges()
    lowers = lower_runs()
    out = sys.stdout
    out.write("""/* Copyright (c) 2026 VillageSQL Contributors
 *
 * This program is free software; you can redistribute it and/or
 * modify it under the terms of the GNU General Public License
 * as published by the Free Software Foundation; either version 2
 * of the License, or (at your option) any later version.
 *
 * This program is distributed in the hope that it will be useful,
 * but WITHOUT ANY WARRANTY; without even the implied warranty of
 * MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.  See the
 * GNU General Public License for more details.
 *
 * You should have received a copy of the GNU General Public License
 * along with this program; if not, see <https://www.gnu.org/licenses/>.
 */

""")
    out.write(f"// Generated by tools/gen_unicode_tables.py from Unicode "
              f"{unicodedata.unidata_version}. Do not edit by hand.\n\n")
    out.write("#ifndef VSQL_TRGM_UNICODE_TABLES_H\n#define VSQL_TRGM_UNICODE_TABLES_H\n\n")
    out.write("#include <cstdint>\n\n")
    out.write("struct CpRange { uint32_t lo, hi; };\n")
    out.write("struct LowerRun { uint32_t lo, hi, stride; int32_t delta; };\n\n")
    out.write("// Code points in general categories L*, Mn, Mc (except variation selectors)\n"
              "// and Nd, sorted.\n")
    out.write("static const CpRange kWordRanges[] = {\n")
    for lo, hi in words:
        out.write(f"  {{0x{lo:04X}, 0x{hi:04X}}},\n")
    out.write("};\n\n")
    out.write("// Simple lowercase: every lo + k * stride <= hi maps to itself + delta.\n")
    out.write("static const LowerRun kLowerRuns[] = {\n")
    for lo, hi, stride, delta in lowers:
        out.write(f"  {{0x{lo:04X}, 0x{hi:04X}, {stride}, {delta}}},\n")
    out.write("};\n\n#endif  // VSQL_TRGM_UNICODE_TABLES_H\n")
    sys.stderr.write(f"word ranges: {len(words)}, lower runs: {len(lowers)}\n")


if __name__ == "__main__":
    main()
